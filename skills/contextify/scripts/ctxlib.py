class Block(object):
    __slots__ = ("begin", "end", "header", "footer", "body", "body_start", "body_end")

    def __init__(self, begin, end, header, footer, body, body_start, body_end):
        self.begin = begin
        self.end = end
        self.header = header
        self.footer = footer
        self.body = body
        self.body_start = body_start
        self.body_end = body_end


def find_block(text):
    """Return (Block or None). Raises CtxError(2) on an unpaired, nested or doubled pair."""
    lines = text.splitlines()
    begins = [i for i, l in enumerate(lines) if BEGIN_RE.match(l)]
    ends = [i for i, l in enumerate(lines) if END_RE.match(l)]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1:
        raise CtxError(
            "conflict: expected one contextify marker pair, found %d begin and %d end "
            "markers (lines %s and %s)" % (
                len(begins), len(ends),
                ", ".join(str(i + 1) for i in begins) or "none",
                ", ".join(str(i + 1) for i in ends) or "none"), 2)
    b, e = begins[0], ends[0]
    if e < b:
        raise CtxError("conflict: contextify:end at line %d precedes begin at line %d"
                       % (e + 1, b + 1), 2)
    inner = lines[b + 1:e]
    header = None
    footer = None
    start = b + 1
    end_body = e
    if inner and HEADER_RE.match(inner[0]):
        header = inner[0]
        start += 1
    body = lines[start:end_body]
    if body and FOOTER_RE.match(body[-1]):
        footer = body[-1]
        body = body[:-1]
        end_body -= 1
        if body and body[-1] == "":
            body = body[:-1]
            end_body -= 1
    return Block(b, e, header, footer, body, start, end_body)


def block_digest(body_lines):
    return digest(list(body_lines))


def header_line(tv, by, at, commit):
    return ("<!-- Generated by contextify %s; writer=%s; at=%s; commit=%s; "
            "regenerate: /contextify update -->" % (tv, by, at, commit or "none"))


def footer_line(date, commit):
    return "verified on %s against %s" % (date, short_commit(commit))


class Meta(object):
    """Everything the header and footer need, in one place."""

    def __init__(self, tool_version_, generated_by, generated_at, commit):
        self.tool_version = tool_version_
        self.generated_by = generated_by
        self.generated_at = generated_at
        self.commit = commit

    @property
    def header(self):
        return header_line(self.tool_version, self.generated_by, self.generated_at,
                           self.commit)

    @property
    def footer(self):
        return footer_line(self.generated_at[:10], self.commit)


