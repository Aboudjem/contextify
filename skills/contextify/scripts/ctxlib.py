def _yaml_block_scalar(lines, idx, base_indent):
    """Collect a YAML block scalar that starts on the line after idx."""
    body = []
    j = idx + 1
    while j < len(lines):
        raw = lines[j]
        if raw.strip() == "":
            body.append("")
            j += 1
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        if indent <= base_indent:
            break
        body.append(raw.strip())
        j += 1
    while body and body[-1] == "":
        body.pop()
    return "\n".join(body), j


def _workflow_jobs(path):
    """A bounded line reader for one workflow. Unfollowable syntax yields 'unverified'."""
    lines = read_lines(path)
    jobs = {}
    in_jobs = False
    current = None
    i = 0
    while i < len(lines):
        raw = lines[i].rstrip("\n")
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            i += 1
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        if indent == 0:
            in_jobs = stripped.rstrip() == "jobs:"
            current = None
            i += 1
            continue
        if not in_jobs:
            i += 1
            continue
        m = re.match(r"^\s{2}([A-Za-z0-9_\-.]+):\s*$", raw)
        if m and indent == 2:
            current = m.group(1)
            jobs[current] = {"runs": [], "working-directory": [], "name": None}
            i += 1
            continue
        if current is None:
            i += 1
            continue
        mname = re.match(r"^\s+name:\s*(.+?)\s*$", raw)
        if mname and indent == 4:
            jobs[current]["name"] = mname.group(1).strip("'\"")
            i += 1
            continue
        mrun = re.match(r"^(\s*)-?\s*run:\s*(.*)$", raw)
        if mrun:
            value = mrun.group(2).strip()
            if value in ("|", ">", "|-", ">-", "|+", ">+"):
                body, i = _yaml_block_scalar(lines, i, indent)
                jobs[current]["runs"].append(body)
                continue
            if value == "":
                jobs[current]["runs"].append("unverified")
            else:
                jobs[current]["runs"].append(value.strip("'\""))
            i += 1
            continue
        mwd = re.match(r"^\s*-?\s*working-directory:\s*(.+?)\s*$", raw)
        if mwd:
            jobs[current]["working-directory"].append(mwd.group(1).strip("'\""))
            i += 1
            continue
        i += 1
    return jobs


def normalize_ci(root):
    wf_dir = os.path.join(root, ".github", "workflows")
    value = {}
    first = None
    if os.path.isdir(wf_dir):
        for name in sorted(os.listdir(wf_dir)):
            if not name.endswith((".yml", ".yaml")):
                continue
            rel = ".github/workflows/" + name
            first = first or rel
            value[rel] = _workflow_jobs(os.path.join(wf_dir, name))
    gitlab = os.path.join(root, ".gitlab-ci.yml")
    if os.path.isfile(gitlab):
        first = first or ".gitlab-ci.yml"
        value[".gitlab-ci.yml"] = {"present": True}
    if not value:
        return []
    return [Record("ci#jobs", first, 1, value)]


def _dockerfile_facts(path):
    froms = []
    exposes = []
    for raw in read_lines(path):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^FROM\s+(.+)$", line, re.IGNORECASE)
        if m:
            rest = m.group(1).split()
            platform = None
            tokens = []
            k = 0
            while k < len(rest):
                if rest[k].startswith("--platform="):
                    platform = rest[k].split("=", 1)[1]
                else:
                    tokens.append(rest[k])
                k += 1
            if not tokens:
                continue
            image = tokens[0]
            image = image.split("@", 1)[0]
            if ":" in image.rsplit("/", 1)[-1]:
                head, _, _tag = image.rpartition(":")
                image = head or image
            alias = None
            if len(tokens) >= 3 and tokens[1].upper() == "AS":
                alias = tokens[2]
            froms.append({"image": image, "as": alias, "platform": platform})
            continue
        m = re.match(r"^EXPOSE\s+(.+)$", line, re.IGNORECASE)
        if m:
            for token in m.group(1).split():
                port, _, proto = token.partition("/")
                exposes.append({"port": port, "proto": proto or "tcp"})
    return {"from": froms, "expose": exposes}


