def build_evidence(root, records, claims, generated_at):
    by_key = {}
    for claim in claims:
        for ref in claim.evidence_refs:
            by_key.setdefault(ref, set()).add(claim.id)
    return {
        "version": EVIDENCE_VERSION,
        "generatedAt": generated_at,
        "records": [r.as_dict(by_key.get(r.key)) for r in records],
    }


def build_stamp(root, records, claims, context_files, meta, scope="."):
    commands = [c.as_dict() for c in claims if c.kind == "command"]
    paths = [c.as_dict() for c in claims if c.kind == "path"]
    evidence_obj = build_evidence(root, records, claims, meta.generated_at)
    stamp = {
        "version": STAMP_VERSION,
        "tool": "contextify",
        "toolVersion": meta.tool_version,
        "generatedAt": meta.generated_at,
        "generatedBy": meta.generated_by,
        "commit": meta.commit,
        "scope": scope,
        "normalizerVersion": NORMALIZER_VERSION,
        "fastKey": fast_key(root),
        "discovery": discovered_paths(root),
        "evidenceFileDigest": digest(evidence_obj),
        "evidence": evidence_digests(records),
        "claims": {"commands": commands, "paths": paths},
        "contextFiles": context_files,
    }
    return stamp, evidence_obj


def entry_from_text(text):
    try:
        body = managed_body_of(text)
    except CtxError:
        body = None
    return {
        "kind": "file",
        "digest": digest_bytes(text),
        "managedBlockDigest": block_digest(body) if body is not None else None,
    }


def context_file_entry(root, rel):
    path = os.path.join(root, rel)
    if os.path.islink(path):
        return {"kind": "symlink", "linkTarget": os.readlink(path),
                "digest": digest_bytes(read_text(path) or ""),
                "managedBlockDigest": None}
    text = read_text(path)
    if text is None:
        return None
    return entry_from_text(text)


