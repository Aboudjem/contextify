def _toml_load(path):
    try:
        import tomllib
    except ImportError:
        return None
    try:
        with open(path, "rb") as fh:
            return tomllib.load(fh)
    except (OSError, ValueError):
        return None


def _toml_section_keys(path, section):
    """Bounded fallback when tomllib is unavailable: read one table's key = value pairs."""
    out = {}
    inside = False
    for raw in read_lines(path):
        line = raw.strip()
        if line.startswith("["):
            inside = line.rstrip() == "[" + section + "]"
            continue
        if not inside or not line or line.startswith("#"):
            continue
        m = re.match(r'^([A-Za-z0-9_\-."]+)\s*=\s*"(.*)"\s*$', line)
        if m:
            out[m.group(1).strip('"')] = m.group(2)
    return out


def normalize_pyproject(root):
    path = os.path.join(root, "pyproject.toml")
    if not os.path.isfile(path):
        return []
    data = _toml_load(path)
    if data is None:
        value = {"project.scripts": _toml_section_keys(path, "project.scripts"),
                 "rest": "unverified"}
    else:
        project = data.get("project") or {}
        poetry = ((data.get("tool") or {}).get("poetry") or {})
        value = {
            "project.scripts": dict(sorted((project.get("scripts") or {}).items())),
            "project.gui-scripts": dict(sorted((project.get("gui-scripts") or {}).items())),
            "poetry.scripts": dict(sorted((poetry.get("scripts") or {}).items())),
        }
    lines = read_lines(path)
    return [Record("pyproject#scripts", "pyproject.toml",
                   line_of(lines, "[project.scripts]") or 1, value)]


def normalize_cargo(root):
    path = os.path.join(root, "Cargo.toml")
    if not os.path.isfile(path):
        return []
    data = _toml_load(path)
    bins = []
    members = []
    if data is not None:
        for entry in data.get("bin") or []:
            if isinstance(entry, dict) and entry.get("name"):
                bins.append({"name": entry["name"], "path": entry.get("path")})
        members = sorted((data.get("workspace") or {}).get("members") or [])
        pkg = data.get("package") or {}
        if os.path.isfile(os.path.join(root, "src", "main.rs")) and pkg.get("name"):
            bins.append({"name": pkg["name"], "path": "src/main.rs"})
    bin_dir = os.path.join(root, "src", "bin")
    if os.path.isdir(bin_dir):
        for name in sorted(os.listdir(bin_dir)):
            if name.endswith(".rs"):
                bins.append({"name": name[:-3], "path": "src/bin/" + name})
    value = {"bins": sorted(bins, key=lambda b: b["name"]), "members": members}
    return [Record("cargo#bins", "Cargo.toml", 1, value)]


def normalize_gomod(root):
    path = os.path.join(root, "go.mod")
