def canonical(obj):
    """Canonical JSON: sorted keys, compact separators, no trailing newline."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def digest(obj):
    return "sha256:" + hashlib.sha256(canonical(obj).encode("utf-8")).hexdigest()


def digest_bytes(data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    return "sha256:" + hashlib.sha256(data).hexdigest()


def claim_id(text, file_rel, cwd):
    raw = "\x00".join((text, file_rel, cwd))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:12]


def git(root, *args, binary=False):
    """Run git in root. Returns None when git fails, so every caller degrades quietly."""
    try:
        p = subprocess.run(["git", *args], cwd=root, stdout=subprocess.PIPE,
                           stderr=subprocess.DEVNULL)
    except (OSError, ValueError):
        return None
    if p.returncode != 0:
        return None
    return p.stdout if binary else p.stdout.decode("utf-8", "replace")


def repo_root(start):
    out = git(start, "rev-parse", "--show-toplevel")
    if not out:
        return None
    root = out.strip()
    return os.path.realpath(root) if root else None


def head_commit(root):
    out = git(root, "rev-parse", "HEAD")
    return out.strip() if out else None


def short_commit(commit):
    return commit[:7] if commit else "none"


def read_text(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return None


def read_lines(path):
    text = read_text(path)
    return text.splitlines() if text is not None else []


def line_of(lines, needle, start=0):
    """1-based line number of the first line containing needle, else None."""
    for i in range(start, len(lines)):
        if needle in lines[i]:
            return i + 1
    return None


