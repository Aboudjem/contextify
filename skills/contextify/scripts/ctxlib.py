def load_json_file(path):
    text = read_text(path)
    if text is None:
        return None
    try:
        return json.loads(text)
    except ValueError:
        return None


def relpath_inside(root, path):
    """The path relative to root, or None when it escapes root."""
    real_root = os.path.realpath(root)
    real = os.path.realpath(path)
    if real == real_root:
        return "."
    prefix = real_root + os.sep
    if not real.startswith(prefix):
        return None
    return real[len(prefix):]


