def collect_evidence(root, extra_paths=()):
    """Every normalizer over the working tree. Returns an ordered list of Record."""
    records = []
    for fn in NORMALIZERS:
        try:
            if fn is normalize_tree:
                records.extend(fn(root, extra_paths))
            else:
                records.extend(fn(root))
        except Exception as exc:  # a broken parser must never break the check
            records.append(Record("error#" + fn.__name__, ".", 1,
                                  "unverified: %s" % exc.__class__.__name__))
    records.sort(key=lambda r: r.key)
    return records


