class Record(object):
    __slots__ = ("key", "file", "line", "value")

    def __init__(self, key, file, line, value):
        self.key = key
        self.file = file
        self.line = line
        self.value = value

    def as_dict(self, claims=None):
        payload = {
            "key": self.key,
            "source": {"file": self.file, "line": self.line},
            "value": self.value,
            "claims": sorted(claims or []),
        }
        return payload


def _pkg_records(root, rel):
    """Every package.json-derived key for one manifest, keyed by its relative path."""
    path = os.path.join(root, rel)
    data = load_json_file(path)
    out = []
    if not isinstance(data, dict):
        return out
    lines = read_lines(path)
    norm = rel.replace(os.sep, "/")

    scripts = data.get("scripts")
    if isinstance(scripts, dict):
        value = {str(k): str(v) for k, v in scripts.items()}
        out.append(Record(norm + "#scripts", norm, line_of(lines, '"scripts"'), value))

    deps = {}
    for group in DEP_GROUPS:
        block = data.get(group)
        if isinstance(block, dict) and block:
            deps[group] = sorted(str(k) for k in block)
    if deps:
        out.append(Record(norm + "#deps", norm, line_of(lines, '"dependencies"'), deps))

    pm = data.get("packageManager")
    if isinstance(pm, str) and pm:
        name = pm.split("@", 1)[0]
        out.append(Record(norm + "#packageManager", norm,
                          line_of(lines, '"packageManager"'), name))

    ws = data.get("workspaces")
    if ws:
        if isinstance(ws, dict):
            value = {k: sorted(v) if isinstance(v, list) else v for k, v in sorted(ws.items())}
        elif isinstance(ws, list):
            value = sorted(str(x) for x in ws)
        else:
            value = "unverified"
        out.append(Record(norm + "#workspaces", norm, line_of(lines, '"workspaces"'), value))

    engines = data.get("engines")
    if isinstance(engines, dict) and engines:
        out.append(Record(norm + "#engines", norm, line_of(lines, '"engines"'),
                          sorted(str(k) for k in engines)))
    return out


def package_manifests(root):
    """Root plus nested manifests, excluding vendored trees. Sorted, root first."""
    found = []
    for rel in eligible_files(root):
        norm = rel.replace(os.sep, "/")
        if os.path.basename(norm) != "package.json":
            continue
        if norm.count("/") > 3:
            continue
        found.append(norm)
    found.sort(key=lambda p: (p.count("/"), p))
    return found


def normalize_packages(root):
    out = []
    for rel in package_manifests(root):
        out.extend(_pkg_records(root, rel))
    return out


