FENCE_RE = re.compile(r"^\s{0,3}(`{3,}|~{3,})\s*([A-Za-z0-9_+-]*)\s*$")
INLINE_RE = re.compile(r"`([^`\n]+)`")
SHELL_LANGS = ("", "sh", "bash", "shell", "console", "zsh")

COMMAND_HEADS = ("npm", "pnpm", "yarn", "bun", "npx", "make", "just", "python", "python3",
                 "cargo", "go", "uv", "poetry", "node", "deno", "pytest", "docker", "git",
                 "gradle", "mvn", "bundle", "rake", "task", "mise")

PM_BUILTINS = ("install", "i", "add", "remove", "rm", "update", "up", "run", "exec", "dlx",
               "create", "init", "publish", "pack", "why", "audit", "outdated", "link",
               "list", "ls", "store", "config", "test", "start", "build", "dev", "fetch",
               "import", "licenses", "patch", "prune", "rebuild", "setup", "upgrade")

CARGO_VERBS = ("build", "check", "clean", "doc", "new", "init", "add", "remove", "run",
               "test", "bench", "update", "search", "publish", "install", "uninstall",
               "fmt", "clippy", "tree", "fix", "vendor", "metadata")

NEGATION_RE = re.compile(
    r"\b(no|not|never|without|instead of|rather than|do not|does not|don't|doesn't|"
    r"deleted|removed|no longer|avoid|deprecated)\b", re.IGNORECASE)

PATH_EXT_RE = re.compile(
    r"\.(ts|tsx|js|jsx|mjs|cjs|json|py|go|rs|java|kt|rb|php|yml|yaml|toml|md|mdc|sh|tf|sql|"
    r"env|gradle|cfg|ini|lock|css|scss|html|txt|xml|proto|graphql)$")
VERSION_RE = re.compile(r"^v?\d+(\.\d+)+$")


class Claim(object):
    __slots__ = ("text", "file", "line", "cwd", "kind", "resolver", "target",
                 "status", "reason", "evidence_refs", "negated")

    def __init__(self, text, file, line, cwd, kind):
        self.text = text
        self.file = file
        self.line = line
        self.cwd = cwd
        self.kind = kind
        self.resolver = "none"
        self.target = None
        self.status = "unverified"
        self.reason = ""
        self.evidence_refs = []
        self.negated = False

    @property
    def id(self):
        return claim_id(self.text, self.file, self.cwd)

    def as_dict(self):
        return {
            "id": self.id,
            "text": self.text,
            "location": {"file": self.file, "line": self.line},
            "cwd": self.cwd,
            "resolver": self.resolver,
            "target": self.target,
            "evidenceRefs": sorted(set(self.evidence_refs)),
            "status": self.status,
        }


def _raw_snippets(text, file_rel):
    """(snippet, line, negated) for every inline span and shell fence body."""
    out = []
    lines = text.splitlines()
    fence = None
    for idx, raw in enumerate(lines, 1):
        m = FENCE_RE.match(raw)
        if m:
            if fence is None:
                fence = m.group(2).lower()
            else:
                fence = None
            continue
        if fence is not None:
            if fence in SHELL_LANGS:
                body = raw.strip()
                if body and not body.startswith("#"):
                    out.append((body.lstrip("$ ").strip(), idx, False))
            continue
        negated = bool(NEGATION_RE.search(raw))
        for span in INLINE_RE.findall(raw):
            span = span.strip()
            if span:
                out.append((span, idx, negated))
    return out


def _split_command(snippet):
    """Split a shell snippet into (cwd_relative, command) pairs. Bounded, no execution."""
    parts = re.split(r"\s*(?:&&|\|\||;|\|)\s*", snippet)
    cwd = "."
    out = []
    for part in parts:
        part = part.strip()
        if not part:
            continue
        m = re.match(r"^cd\s+([^\s]+)$", part)
        if m:
            target = m.group(1).strip("'\"")
            cwd = target if cwd == "." else os.path.normpath(os.path.join(cwd, target))
            continue
        while True:
            m = re.match(r"^[A-Za-z_][A-Za-z0-9_]*=\S*\s+(.*)$", part)
            if not m:
                break
            part = m.group(1).strip()
        if part:
            out.append((cwd, part))
    return out


def _looks_like_path(token):
    if not token or " " in token or "://" in token:
        return False
    if token.startswith("-") or token.startswith("/") or token.startswith("~"):
        return False
    if "#" in token or "*" in token or "$" in token or "{" in token:
        return False
    if VERSION_RE.match(token):
        return False
    return "/" in token or bool(PATH_EXT_RE.search(token))


def extract_claims(text, file_rel, scope="."):
    claims = []
    seen = set()
    for snippet, line, negated in _raw_snippets(text, file_rel):
        head = snippet.split()[0] if snippet.split() else ""
        if " " in snippet or head in COMMAND_HEADS:
            for cwd, command in _split_command(snippet):
                token = command.split()[0] if command.split() else ""
                if token not in COMMAND_HEADS:
                    continue
                key = (command, cwd, file_rel)
                if key in seen:
                    continue
                seen.add(key)
                claim = Claim(command, file_rel, line, cwd, "command")
                claim.negated = negated
                claims.append(claim)
        elif _looks_like_path(snippet):
            key = (snippet, ".", file_rel)
            if key in seen:
                continue
            seen.add(key)
            claim = Claim(snippet, file_rel, line, scope, "path")
            claim.negated = negated
            claims.append(claim)
    return claims


def _scripts_for(root, cwd):
    rel = "package.json" if cwd in (".", "") else os.path.join(cwd, "package.json")
    data = load_json_file(os.path.join(root, rel))
    if not isinstance(data, dict):
        return None, rel.replace(os.sep, "/")
    scripts = data.get("scripts")
    return (scripts if isinstance(scripts, dict) else {}), rel.replace(os.sep, "/")


def _resolve_script(claim, root, name, manager):
    scripts, rel = _scripts_for(root, claim.cwd)
    claim.resolver = manager + "-run"
    claim.target = "scripts." + name
    claim.evidence_refs.append(rel + "#scripts")
    if scripts is None:
        claim.status = "unverified"
        claim.reason = "no package.json at %s" % (claim.cwd or ".")
        return
    if name in scripts:
        claim.status = "verified"
        return
    claim.status = "stale"
    claim.reason = "%s declares no script %s" % (rel, name)


def _resolve_make(claim, root, target):
    claim.resolver = "make-target"
    claim.target = target
    path = None
    for name in ("Makefile", "makefile", "GNUmakefile"):
        candidate = os.path.join(root, claim.cwd if claim.cwd != "." else "", name)
        if os.path.isfile(candidate):
            path = candidate
            break
    if path is None:
        claim.status = "unverified"
        claim.reason = "no Makefile at %s" % (claim.cwd or ".")
        return
    claim.evidence_refs.append("makefile#targets")
    targets = _makefile_targets(path)
    if target in targets:
        claim.status = "verified"
    else:
        claim.status = "stale"
        claim.reason = "%s declares no target %s" % (os.path.basename(path), target)


def _resolve_just(claim, root, recipe):
    claim.resolver = "just-recipe"
    claim.target = recipe
    path = None
    for name in ("justfile", "Justfile", ".justfile"):
        candidate = os.path.join(root, claim.cwd if claim.cwd != "." else "", name)
        if os.path.isfile(candidate):
            path = candidate
            break
    if path is None:
        claim.status = "unverified"
        claim.reason = "no justfile at %s" % (claim.cwd or ".")
        return
    claim.evidence_refs.append("justfile#recipes")
    recipes = _justfile_recipes(path)
    if recipe in recipes:
        claim.status = "verified"
    else:
        claim.status = "stale"
        claim.reason = "%s declares no recipe %s" % (os.path.basename(path), recipe)


def _resolve_python_module(claim, root, module):
    claim.resolver = "python-module"
    claim.target = module
    base = os.path.join(root, claim.cwd if claim.cwd != "." else "")
    as_path = module.replace(".", os.sep)
    if (os.path.isfile(os.path.join(base, as_path + ".py"))
            or os.path.isfile(os.path.join(base, as_path, "__main__.py"))):
        claim.status = "verified"
        claim.evidence_refs.append("tree#depth2")
        return
    claim.status = "unverified"
    claim.reason = "no local module %s; a dependency name alone does not prove it" % module


def _resolve_path(claim, root):
    claim.resolver = "tracked-file"
    base = root if claim.cwd in (".", "") else os.path.join(root, claim.cwd)
    candidate = os.path.join(base, claim.text)
    inside = relpath_inside(root, candidate) if os.path.exists(candidate) else None
    claim.target = claim.text
    claim.evidence_refs.append("tree#depth2")
    if os.path.exists(candidate):
        if inside is None:
            claim.status = "stale"
            claim.reason = "%s resolves outside the scope" % claim.text
        else:
            claim.status = "verified"
        return
    claim.status = "stale"
    claim.reason = "%s does not exist" % claim.text


def resolve_claim(claim, root):
    tokens = claim.text.split()
    if not tokens:
        claim.status = "unverified"
        return claim
    head = tokens[0]

    if claim.kind == "path":
        _resolve_path(claim, root)
    elif head == "npm":
        if len(tokens) >= 3 and tokens[1] == "run":
            _resolve_script(claim, root, tokens[2], "npm")
        elif len(tokens) >= 2 and tokens[1] in ("test", "start"):
            _resolve_script(claim, root, tokens[1], "npm")
        else:
            claim.resolver = "npm-builtin"
            claim.status = "unverified"
            claim.reason = "not a script invocation"
    elif head in ("pnpm", "yarn", "bun"):
        if len(tokens) >= 3 and tokens[1] == "run":
            _resolve_script(claim, root, tokens[2], head)
        elif len(tokens) >= 3 and tokens[1] in ("exec", "dlx"):
            claim.resolver = head + "-exec"
            claim.status = "unverified"
            claim.reason = "%s %s resolves at runtime" % (head, tokens[1])
        elif len(tokens) >= 2:
            scripts, rel = _scripts_for(root, claim.cwd)
            name = tokens[1]
            claim.resolver = head + "-shorthand"
            claim.target = "scripts." + name
            claim.evidence_refs.append(rel + "#scripts")
            if scripts is None:
                claim.status = "unverified"
                claim.reason = "no package.json at %s" % (claim.cwd or ".")
            elif name in scripts:
                claim.status = "verified"
            elif name in PM_BUILTINS:
                claim.status = "unverified"
                claim.reason = "%s is a %s built-in; explicit run is required to verify" % (
                    name, head)
            else:
                claim.status = "stale"
                claim.reason = "%s declares no script %s" % (rel, name)
        else:
            claim.status = "unverified"
    elif head == "npx":
        claim.resolver = "npx"
        claim.target = tokens[1] if len(tokens) > 1 else None
        bin_path = os.path.join(root, "node_modules", ".bin", tokens[1]) if len(tokens) > 1 \
            else None
        deps = set()
        data = load_json_file(os.path.join(root, "package.json"))
        if isinstance(data, dict):
            for group in DEP_GROUPS:
                block = data.get(group)
                if isinstance(block, dict):
                    deps |= set(block)
        if bin_path and os.path.exists(bin_path):
            claim.status = "verified"
            claim.evidence_refs.append("tree#depth2")
        elif len(tokens) > 1 and tokens[1] in deps:
            claim.status = "verified"
            claim.evidence_refs.append("package.json#deps")
        else:
            claim.status = "unverified"
            claim.reason = "npx downloads on demand; nothing in the repository proves it"
    elif head == "make":
        args = [t for t in tokens[1:] if not t.startswith("-")]
        if args:
            _resolve_make(claim, root, args[0])
        else:
            claim.resolver = "make-default"
            claim.status = "unverified"
    elif head == "just":
        args = [t for t in tokens[1:] if not t.startswith("-")]
        if args:
            _resolve_just(claim, root, args[0])
        else:
            claim.resolver = "just-default"
            claim.status = "unverified"
    elif head in ("python", "python3"):
        if len(tokens) >= 3 and tokens[1] == "-m":
            _resolve_python_module(claim, root, tokens[2])
        elif len(tokens) >= 2 and not tokens[1].startswith("-"):
            sub = Claim(tokens[1], claim.file, claim.line, claim.cwd, "path")
            _resolve_path(sub, root)
            claim.resolver = "python-script"
            claim.target = tokens[1]
            claim.status = sub.status
            claim.reason = sub.reason
            claim.evidence_refs.extend(sub.evidence_refs)
        else:
            claim.status = "unverified"
    elif head == "cargo":
        verb = tokens[1] if len(tokens) > 1 else ""
        claim.resolver = "cargo-verb"
        claim.target = verb
        if not os.path.isfile(os.path.join(root, "Cargo.toml")):
            claim.status = "unverified"
            claim.reason = "no Cargo.toml in scope"
        elif verb in CARGO_VERBS:
            claim.status = "verified"
            claim.evidence_refs.append("cargo#bins")
        else:
            claim.status = "unverified"
            claim.reason = "%s is not a known cargo verb" % verb
    elif head == "go":
        claim.resolver = "go-module"
        claim.target = " ".join(tokens[1:2])
        if not os.path.isfile(os.path.join(root, "go.mod")):
            claim.status = "unverified"
            claim.reason = "no go.mod in scope"
        else:
            claim.status = "verified"
            claim.evidence_refs.append("go.mod#module+go")
    elif head in ("uv", "poetry"):
        claim.resolver = head + "-run"
        claim.status = "unverified"
        claim.reason = "%s run targets are not resolved in 0.1.0" % head
    else:
        claim.resolver = "none"
        claim.status = "unverified"
        claim.reason = "no resolver for %s" % head

    if claim.status == "stale" and claim.negated:
        claim.status = "unverified"
        claim.reason = "documented as absent on this line"
    return claim


def claims_for_file(root, rel, scope="."):
    text = read_text(os.path.join(root, rel))
    if text is None:
        return []
    claims = extract_claims(text, rel.replace(os.sep, "/"), scope)
    for claim in claims:
        resolve_claim(claim, root)
    return claims


