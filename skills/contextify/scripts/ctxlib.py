def envelope(hook, text):
    """One physical line of JSON for the agent that asked for it."""
    if not text:
        return ""
    if hook == "cursor":
        return json.dumps({"additional_context": text}, ensure_ascii=False)
    if hook == "codex":
        return json.dumps({"hookSpecificOutput": {
            "hookEventName": "SessionStart", "additionalContext": text}}, ensure_ascii=False)
    # claude and gemini share one shape.
    return json.dumps({"hookSpecificOutput": {
        "hookEventName": "SessionStart", "additionalContext": text}}, ensure_ascii=False)


def json_report(result):
    if result.status == "nostamp":
        return {"status": "nostamp", "changed": [], "removed": [], "added": [], "stale": [],
                "next": "/contextify init"}
    payload = {
        "status": result.status,
        "changed": result.changed,
        "removed": result.removed,
        "added": result.added,
        "stale": result.stale,
        "next": "/contextify update" if result.status == "drift" else "",
    }
    if result.edited:
        payload["edited"] = result.edited
    if result.missing:
        payload["missing"] = result.missing
    return payload
