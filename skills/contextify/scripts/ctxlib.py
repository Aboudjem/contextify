def read_lines(path):
    text = read_text(path)
    return text.splitlines() if text is not None else []


def line_of(lines, needle, start=0):
    """1-based line number of the first line containing needle, else None."""
    for i in range(start, len(lines)):
        if needle in lines[i]:
            return i + 1
    return None


