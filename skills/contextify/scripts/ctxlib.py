def _detail_lines(key, old, new):
    out = []
    if key.endswith("#scripts") and isinstance(old, dict) and isinstance(new, dict):
        for name in sorted(set(old) - set(new)):
            out.append(("Removed", "script " + name))
        for name in sorted(set(new) - set(old)):
            out.append(("Added", "script " + name))
        for name in sorted(set(old) & set(new)):
            if old[name] != new[name]:
                out.append(("Changed", "script %s body" % name))
    elif key.endswith("#deps") and isinstance(old, dict) and isinstance(new, dict):
        old_names = set()
        new_names = set()
        for group, names in old.items():
            old_names |= set(names)
        for group, names in new.items():
            new_names |= set(names)
        for name in sorted(old_names - new_names):
            out.append(("Removed", "dependency " + name))
        for name in sorted(new_names - old_names):
            out.append(("Added", "dependency " + name))
    elif key.endswith("#keys") and isinstance(old, dict) and isinstance(new, dict):
        old_names = set()
        new_names = set()
        for _f, names in old.items():
            old_names |= set(names)
        for _f, names in new.items():
            new_names |= set(names)
        for name in sorted(old_names - new_names):
            out.append(("Removed", "env key " + name))
        for name in sorted(new_names - old_names):
            out.append(("Added", "env key " + name))
    return out


ESCAPE_RE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


def _sanitize(text):
    return ESCAPE_RE.sub(lambda m: "\\x%02x" % ord(m.group(0)), text)


class CheckResult(object):
    def __init__(self):
        self.status = "fresh"
        self.scope = "."
        self.changed = []
        self.removed = []
        self.added = []
        self.stale = []
        self.edited = []
        self.missing = []
        self.pointer = []
        self.unverified = []
        self.details = []

    @property
    def has_findings(self):
        return bool(self.changed or self.removed or self.added or self.stale
                    or self.edited or self.missing or self.pointer)


def run_check(root, strict=False):
    """The slow path. Returns a CheckResult; raises CtxError for a broken check."""
    result = CheckResult()
    stamp = load_json_file(os.path.join(root, STAMP_REL))
    if stamp is None:
        result.status = "nostamp"
        return result
    if stamp.get("normalizerVersion") not in (None, NORMALIZER_VERSION):
        raise CtxError("stamp normalizerVersion %r is not supported by this build"
                       % stamp.get("normalizerVersion"), 1)
    result.scope = stamp.get("scope") or "."

    evidence = load_json_file(os.path.join(root, EVIDENCE_REL)) or {}
    old_values = {r.get("key"): r.get("value")
                  for r in (evidence.get("records") or []) if isinstance(r, dict)}

    records = collect_evidence(root)
    new_digests = evidence_digests(records)
    new_values = {r.key: r.value for r in records}
    old_digests = stamp.get("evidence") or {}

    for key in sorted(set(old_digests) | set(new_digests)):
        if key not in new_digests:
            result.removed.append(key)
        elif key not in old_digests:
            result.added.append(key)
        elif old_digests[key] != new_digests[key]:
            result.changed.append(key)
            result.details.extend(
                _detail_lines(key, old_values.get(key), new_values.get(key)))

    context_files = stamp.get("contextFiles") or {}
    for rel in sorted(context_files):
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            result.missing.append(rel)
            continue
        entry = context_files[rel] or {}
        text = read_text(path)
        if text is None:
            result.missing.append(rel)
            continue
        try:
            body = managed_body_of(text)
        except CtxError as exc:
            result.edited.append("%s %s" % (rel, exc.message))
            continue
        recorded = entry.get("managedBlockDigest")
        if recorded and body is not None and block_digest(body) != recorded:
            result.edited.append(rel)
        if rel == CLAUDE_MD:
            first = text.splitlines()[0] if text.splitlines() else ""
            if first.strip() != "@AGENTS.md":
                result.pointer.append("%s:1 no longer imports AGENTS.md" % rel)

    for rel in sorted(context_files):
        if not os.path.exists(os.path.join(root, rel)):
            continue
        for claim in claims_for_file(root, rel, result.scope):
            if claim.status == "stale":
                result.stale.append({"file": claim.file, "line": claim.line,
                                     "text": claim.text, "reason": claim.reason})
            elif claim.status == "unverified":
                result.unverified.append({"file": claim.file, "line": claim.line,
                                          "text": claim.text, "reason": claim.reason})

    if result.has_findings:
        result.status = "drift"
    elif strict and result.unverified:
        result.status = "drift"
    else:
        result.status = "fresh"
    return result


def notice_lines(result):
    """The D11 drift notice: dead claims first, bounded to 12 lines and 2,048 bytes."""
    findings = []
    for item in result.stale:
        findings.append((label("Stale"),
                         "%s:%s references %s" % (item["file"], item["line"],
                                                  _sanitize(item["text"]))))
    for rel in result.missing:
        findings.append((label("Missing"), "%s no longer exists" % rel))
    for item in result.pointer:
        findings.append((label("Pointer"), _sanitize(item)))
    for key in result.changed:
        findings.append((label("Changed"), key))
    for tag, text in result.details:
        findings.append((label(tag), _sanitize(text)))
    for key in result.removed:
        findings.append((label("Removed"), key))
    for key in result.added:
        findings.append((label("Added"), key))
    for rel in result.edited:
        findings.append((label("Edited"), "%s managed block was edited by hand" % rel))

    head = ["contextify: drift", label("Scope") + result.scope]
    if result.stale:
        tail = [label("Files") + "0 written",
                label("Next") + "/contextify update",
                label("Accept") + "unavailable until the stale command is corrected"]
    else:
        tail = [label("Files") + "0 written",
                label("Next") + "/contextify update, or /contextify accept if the docs "
                                "are still right"]

    room = NOTICE_MAX_LINES - len(head) - len(tail)
    if len(findings) > room:
        kept = findings[:max(room - 1, 0)]
        kept.append((label("More"), "+%d findings" % (len(findings) - len(kept))))
        findings = kept

    lines = head + [tag + text for tag, text in findings] + tail
    while len("\n".join(lines).encode("utf-8")) > NOTICE_MAX_BYTES and len(findings) > 1:
        findings = findings[:-1]
        lines = head + [tag + text for tag, text in findings] + tail
    return lines


def notice_text(result):
    return "\n".join(notice_lines(result))


