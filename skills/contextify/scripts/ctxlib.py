MANIFEST_NAMES = ("package.json", "pyproject.toml", "Cargo.toml", "go.mod", "pom.xml",
                  "build.gradle", "build.gradle.kts", "setup.py", "Gemfile")


def build_units(root):
    units = set()
    for rel in eligible_files(root):
        norm = rel.replace(os.sep, "/")
        base = os.path.basename(norm)
        if base not in MANIFEST_NAMES:
            continue
        directory = os.path.dirname(norm) or "."
        if base == "package.json":
            data = load_json_file(os.path.join(root, rel))
            if not isinstance(data, dict):
                continue
            if not (data.get("scripts") or data.get("bin") or data.get("main")
                    or data.get("name")):
                continue
        units.add(directory)
    return sorted(units)


def has_workspace(root):
    if os.path.isfile(os.path.join(root, "pnpm-workspace.yaml")):
        return True
    for name in ("lerna.json", "nx.json", "turbo.json", "go.work"):
        if os.path.isfile(os.path.join(root, name)):
            return True
    data = load_json_file(os.path.join(root, "package.json"))
    if isinstance(data, dict) and data.get("workspaces"):
        return True
    cargo = _toml_load(os.path.join(root, "Cargo.toml"))
    if isinstance(cargo, dict) and (cargo.get("workspace") or {}).get("members"):
        return True
    return False


