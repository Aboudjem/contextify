def atomic_write(path, text):
    directory = os.path.dirname(os.path.abspath(path)) or "."
    if not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".contextify-", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def write_if_changed(path, text):
    """True when the file was written, False when it already held exactly these bytes."""
    current = read_text(path) if os.path.exists(path) else None
    if current == text:
        return False
    atomic_write(path, text)
    return True


GITIGNORE_BLOCK = ["# START contextify", ".contextify/draft/", ".contextify/journal.json",
                   "# END contextify"]


def gitignore_merged_text(root):
    """The .gitignore contextify would write, idempotently. Never reorders human lines."""
    path = os.path.join(root, ".gitignore")
    existing = read_text(path)
    block = "\n".join(GITIGNORE_BLOCK)
    if existing is None:
        return block + "\n"
    if "# START contextify" in existing:
        lines = existing.splitlines()
        start = lines.index("# START contextify")
        try:
            end = lines.index("# END contextify", start)
        except ValueError:
            end = start
        merged = lines[:start] + GITIGNORE_BLOCK + lines[end + 1:]
        return "\n".join(merged).rstrip("\n") + "\n"
    return existing.rstrip("\n") + "\n\n" + block + "\n"


