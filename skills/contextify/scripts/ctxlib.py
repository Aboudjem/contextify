def normalize_tsconfig(root):
    path = os.path.join(root, "tsconfig.json")
    if not os.path.isfile(path):
        return []
    text = read_text(path) or ""
    # tsconfig.json is JSONC in practice. Strip line comments and trailing commas, bounded.
    stripped = re.sub(r"(?m)^\s*//.*$", "", text)
    stripped = re.sub(r"/\*.*?\*/", "", stripped, flags=re.DOTALL)
    stripped = re.sub(r",(\s*[}\]])", r"\1", stripped)
    try:
        data = json.loads(stripped)
    except ValueError:
        return [Record("tsconfig#paths+strict+target+module", "tsconfig.json", 1, "unverified")]
    opts = data.get("compilerOptions") or {}
    value = {
        "paths": opts.get("paths"),
        "strict": opts.get("strict"),
        "target": opts.get("target"),
        "module": opts.get("module"),
        "extends": data.get("extends"),
    }
    lines = read_lines(path)
    return [Record("tsconfig#paths+strict+target+module", "tsconfig.json",
                   line_of(lines, '"compilerOptions"') or 1, value)]


ENV_KEY_RE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=")


def normalize_env_example(root):
    """Variable names only. The bytes after '=' are never kept, hashed or stored."""
    value = {}
    first = None
    for name in (".env.example", ".env.sample", ".env.template"):
        path = os.path.join(root, name)
        if not os.path.isfile(path):
            continue
        keys = []
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                for raw in fh:
                    m = ENV_KEY_RE.match(raw)
                    if m:
                        keys.append(m.group(1))
                    del raw
        except OSError:
            continue
        first = first or name
        value[name] = sorted(set(keys))
    if not value:
        return []
    return [Record("env.example#keys", first, 1, value)]


def normalize_tree(root, extra_paths=()):
    """Depth-two names from git, tracked and non-ignored untracked alike.

    Both halves come from git ls-files, so a file that moves from untracked to tracked
    changes nothing. That matters because contextify writes .gitignore itself, and a
    generator whose own output reports drift the moment it is committed gets switched
    off. extra_paths lets a writer hash the tree it is about to produce.
    """
    entries = set()
    for rel in list(eligible_files(root)) + list(extra_paths):
        if is_excluded(rel):
            continue
        parts = rel.replace(os.sep, "/").split("/")
        if len(parts) == 1:
            entries.add(parts[0])
        else:
            entries.add(parts[0] + "/" + parts[1] + ("/" if len(parts) > 2 else ""))
    return [Record("tree#depth2", ".", 1, sorted(entries))]


MAKE_TARGET_RE = re.compile(r"^([A-Za-z0-9_][A-Za-z0-9_.\-/ ]*):(?!=)\s*(.*)$")


def _makefile_targets(path):
    targets = {}
    lines = read_lines(path)
    current = None
    for raw in lines:
        if raw.startswith("\t"):
            if current:
                targets[current]["recipe"].append(raw[1:].strip())
            continue
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        m = MAKE_TARGET_RE.match(line)
        if not m:
            current = None
            continue
        names = m.group(1).split()
        prereqs = m.group(2).split()
        for name in names:
            if name.startswith("."):
                continue
            targets.setdefault(name, {"prereqs": prereqs, "recipe": []})
            current = name
    return targets


def normalize_makefile(root):
    for name in ("Makefile", "makefile", "GNUmakefile"):
        path = os.path.join(root, name)
        if os.path.isfile(path):
            return [Record("makefile#targets", name, 1, _makefile_targets(path))]
    return []


JUST_RECIPE_RE = re.compile(r"^([A-Za-z0-9_][A-Za-z0-9_\-]*)(\s+[^:=]*)?:(?!=)\s*(.*)$")


def _justfile_recipes(path):
    recipes = {}
    current = None
    for raw in read_lines(path):
        if raw.startswith((" ", "\t")):
            if current:
                recipes[current]["recipe"].append(raw.strip())
            continue
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        m = JUST_RECIPE_RE.match(line)
        if not m:
            current = None
            continue
        name = m.group(1)
        params = (m.group(2) or "").split()
        recipes[name] = {"params": params, "recipe": []}
        current = name
    return recipes


