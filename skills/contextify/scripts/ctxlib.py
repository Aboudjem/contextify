def atomic_write(path, text, root=None):
    directory = os.path.dirname(os.path.abspath(path)) or "."
    if not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".contextify-", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        if root is not None:
            safe_path(root, os.path.relpath(path, root))
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def write_if_changed(path, text):
    """True when the file was written, False when it already held exactly these bytes."""
    current = read_text(path) if os.path.exists(path) else None
    if current == text:
        return False
    atomic_write(path, text)
    return True


GITIGNORE_BLOCK = ["# START contextify", ".contextify/draft/", ".contextify/journal.json",
                   "# END contextify"]


def gitignore_merged_text(root):
    """The .gitignore contextify would write, idempotently. Never reorders human lines."""
    path = os.path.join(root, ".gitignore")
    existing = read_text(path)
    block = "\n".join(GITIGNORE_BLOCK)
    if existing is None:
        return block + "\n"
    lines = existing.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.rstrip("\r\n") == "# START contextify"]
    if starts:
        start = starts[0]
        ends = [i for i in range(start + 1, len(lines)) if lines[i].rstrip("\r\n") == "# END contextify"]
        if not ends:
            raise CtxError("refused: incomplete contextify gitignore block", 4)
        end = ends[0]
        if [l.rstrip("\r\n") for l in lines[start:end + 1]] == GITIGNORE_BLOCK:
            return existing
        return "".join(lines[:start]) + block + "\n" + "".join(lines[end + 1:])
    separator = "" if existing.endswith("\n") else "\n"
    return existing + separator + "\n" + block + "\n"


